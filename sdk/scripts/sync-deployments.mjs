import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

// contracts/ in the monorepo; the repository root in verio-protocol, where this package is sdk/.
const monorepo = resolve(import.meta.dirname, '../../../contracts/deployments')
const dir = existsSync(monorepo) ? monorepo : resolve(import.meta.dirname, '../../deployments')
const out = resolve(import.meta.dirname, '../src/deployments.ts')
// Key in contracts/deployments/<chainId>.json → whether it holds an address (quoted) or a block number.
const keys = { proofOfContribution: true, startBlock: false, resourceRegistry: true, resourceRegistryStartBlock: false, payeeVaultFactory: true }
const entries = readdirSync(dir)
  .filter((f) => /^\d+\.json$/.test(f))
  // 31337 is the local anvil chain the tests deploy to; its addresses must not ship in the package.
  .filter((f) => f !== '31337.json')
  .map((f) => [Number(f.replace('.json', '')), JSON.parse(readFileSync(resolve(dir, f), 'utf8'))])
  .sort((a, b) => a[0] - b[0])
const body = entries
  .map(([id, d]) => {
    const fields = Object.entries(keys)
      .filter(([k]) => d[k] !== undefined)
      .map(([k, isAddress]) => `${k}: ${isAddress ? `'${d[k]}'` : d[k]}`)
    return `  ${id}: { ${fields.join(', ')} },`
  })
  .join('\n')
writeFileSync(
  out,
  `// generated by scripts/sync-deployments.mjs — do not edit
import type { Address } from 'viem'

export type Deployment = {
  proofOfContribution?: Address
  startBlock?: number
  resourceRegistry?: Address
  resourceRegistryStartBlock?: number
  payeeVaultFactory?: Address
}

export const deployments: Readonly<Record<number, Deployment>> = {
${body}
}
`,
)
console.log(`synced ${entries.length} deployment(s) → ${out}`)
